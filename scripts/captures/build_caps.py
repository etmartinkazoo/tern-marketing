"""Turn captures of each screen in every theme into one HTML fragment per screen whose
colors are CSS variables, plus one stylesheet with each theme's values.
usage: build_caps.py <capdir> <outdir-fragments> <out-css>"""
import re, sys, os, html, json
capdir, fragdir, cssout = sys.argv[1:4]
THEMES = ["tokyo-night", "catppuccin", "gruvbox", "nord", "everforest", "kanagawa", "rose-pine"]
SCREENS = ["mail", "calendar", "quickadd", "people", "compose", "snooze", "keys"]

def theme_bgfg(t):
    d = {}
    for l in open(f"{capdir}/../themes/{t}/colors.toml"):
        k, _, v = l.partition("=")
        d[k.strip()] = v.strip().strip('"')
    return d["background"], d["foreground"]

def parse(path):
    """-> list of rows, each a list of (ch, fg, bg, attrs)"""
    rows = []
    for line in open(path, encoding="utf-8").read().rstrip("\n").split("\n"):
        st = {}; cells = []
        for part in re.split(r"(\x1b\[[0-9;]*m)", line):
            if part.startswith("\x1b["):
                codes = [int(x) if x else 0 for x in part[2:-1].split(";")] or [0]
                j = 0
                while j < len(codes):
                    c = codes[j]
                    if c == 0: st = {}
                    elif c in (1, 2, 3, 4, 7): st[c] = 1
                    elif c == 22: st.pop(1, None); st.pop(2, None)
                    elif c == 23: st.pop(3, None)
                    elif c == 24: st.pop(4, None)
                    elif c == 27: st.pop(7, None)
                    elif c in (38, 48):
                        k = "fg" if c == 38 else "bg"
                        if codes[j+1] == 2: st[k] = "#%02x%02x%02x" % tuple(codes[j+2:j+5]); j += 4
                        else: j += 2
                    elif c == 39: st.pop("fg", None)
                    elif c == 49: st.pop("bg", None)
                    j += 1
            else:
                for ch in part:
                    fg, bg = st.get("fg"), st.get("bg")
                    if st.get(7): fg, bg = (bg or "BG"), (fg or "FG")
                    attrs = "".join(a for a, k in (("b", 1), ("d", 2), ("i", 3), ("u", 4)) if st.get(k))
                    cells.append((ch, fg or "FG", bg, attrs))
        rows.append(cells)
    return rows

slots = {}      # tuple of colors across themes -> var name
def slot(tup):
    if tup not in slots: slots[tup] = "--k%d" % len(slots)
    return slots[tup]
classes = {}    # (fgvar, bgvar, attrs) -> class
def klass(key):
    if key not in classes: classes[key] = "c%d" % len(classes)
    return classes[key]

bgfg = {t: theme_bgfg(t) for t in THEMES}
def resolve(c, t):
    if c == "FG": return bgfg[t][1]
    if c == "BG": return bgfg[t][0]
    return c

os.makedirs(fragdir, exist_ok=True)
for screen in SCREENS:
    grids = {t: parse(f"{capdir}/{t}/{screen}.txt") for t in THEMES}
    base = grids[THEMES[0]]
    out_rows = []
    mism = 0
    for r, row in enumerate(base):
        spans = []
        for ci, (ch, fg, bg, attrs) in enumerate(row):
            def other(t, idx):
                g = grids[t]
                try: return g[r][ci][idx]
                except IndexError: return None
            fgt = tuple(resolve(other(t, 1) or fg, t) for t in THEMES)
            fv = slot(fgt)
            bv = None
            if bg is not None or any(other(t, 2) for t in THEMES):
                bgt = tuple(resolve(other(t, 2) or "BG", t) for t in THEMES)
                bv = slot(bgt)
            k = klass((fv, bv, attrs))
            if spans and spans[-1][0] == k: spans[-1][1].append(ch)
            else: spans.append((k, [ch]))
        out_rows.append("".join('<span class="%s">%s</span>' % (k, html.escape("".join(cs))) for k, cs in spans))
    open(f"{fragdir}/{screen}.html", "w", encoding="utf-8").write(
        '<pre class="tui-grid" aria-hidden="true">' + "\n".join(out_rows) + "</pre>\n")

css = ["/* Generated by build_caps.py from real tern --demo captures. */"]
for (fv, bv, attrs), name in classes.items():
    d = ["color:var(%s)" % fv]
    if bv: d.append("background:var(%s)" % bv)
    if "b" in attrs: d.append("font-weight:700")
    if "i" in attrs: d.append("font-style:italic")
    if "u" in attrs: d.append("text-decoration:underline")
    if "d" in attrs: d.append("opacity:.6")
    css.append(".tui-grid .%s{%s}" % (name, ";".join(d)))
for i, t in enumerate(THEMES):
    decl = ";".join("%s:%s" % (v, tup[i]) for tup, v in slots.items())
    sel = ':root,[data-theme="%s"]' % t if i == 0 else '[data-theme="%s"]' % t
    css.append("%s{%s}" % (sel, decl))
open(cssout, "w").write("\n".join(css) + "\n")
print(len(slots), "color slots,", len(classes), "classes")
